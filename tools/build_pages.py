def crumbs(items):
    out = []
    for i, (name, path) in enumerate(items):
        if path and i < len(items) - 1:
            out.append(f'<a href="{path}">{H.escape(name)}</a>')
        else:
            out.append(f'<span aria-current="page">{H.escape(name)}</span>')
    return '<nav class="crumbs" aria-label="Breadcrumb">' + ' <span aria-hidden="true">/</span> '.join(out) + "</nav>"

def crumbs_ld(items):
    return {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": n, "item": SITE + (p or "/")} for i, (n, p) in enumerate(items)]}

def faq_ld(path, faq):
    return {"@type": "FAQPage", "@id": SITE + path + "#faq", "mainEntity": [
        {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in faq]}

